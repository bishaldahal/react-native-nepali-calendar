/**
 * Returns the number of days in a given BS month.
 *
 * @param bsYear - The BS year (must be within BS_EPOCH_YEAR..BS_MAX_YEAR).
 * @param bsMonth - The BS month (1–12).
 * @returns Number of days in that month, or `undefined` if out of range.
 */
export function getDaysInBsMonth(
  bsYear: number,
  bsMonth: number
): number | undefined {
  const yearData = BS_MONTH_DAYS[bsYear];
  if (!yearData) return undefined;
  return yearData[bsMonth - 1];
}

/**
 * Returns the total number of days in a given BS year.
 *
 * @param bsYear - The BS year.
 * @returns Total days in the year, or `undefined` if out of range.
 */
export function getDaysInBsYear(bsYear: number): number | undefined {
  const yearData = BS_MONTH_DAYS[bsYear];
  if (!yearData) return undefined;
  return yearData.reduce((sum, days) => sum + days, 0);
}
